def gate_prereq_template(p: StrategyProposal, reality: dict) -> dict:
    """Generate 5-gate prereq checklist for this proposal."""
    return {
        'Gate_1_BT_LIVE_parity_audit': {
            'required': True,
            'specific_actions': [
                f'List ALL state-changing methods in LIVE bot (matches mechanism={p.feature.mechanism})',
                'Build 1:1 mapping table: LIVE method line → BT analog line',
                'No method should be missing analog (use ast_parity_analyzer.py)',
                'auto_size_from_balance config? → BT must track balance dynamically',
            ],
            'pass_criterion': 'Gate1 audit score = 1.0 (all LIVE behaviors mapped)',
            'gate1_readiness_score': reality['dimensions']['gate1_readiness']['score'],
        },
        'Gate_2_statistical_validation': {
            'required': True,
            'specific_actions': [
                'n ≥ 20 비겹침 multi-window BT',
                'mean + median both positive',
                'one-sided sign test p < 0.05',
                'WF 5-fold expanding window: ≥3/5 PASS',
                'Bootstrap 1000 × 3-day window: pos_rate ≥ 50%',
                '3-way train/val/test split: all 3 positive',
            ],
            'pass_criterion': 'All statistical tests PASS',
        },
        'Gate_3_data_source_match': {
            'required': True,
            'specific_actions': [
                f'BT data must be from {p.user_infrastructure} (LIVE exchange)',
                'If multiple sources used → caveat + cross-validation',
                'LIVE config snapshot (yaml hash) verified inside BT script',
            ],
            'pass_criterion': 'BT data source = LIVE exchange',
        },
        'Gate_4_paper_trade': {
            'required': True,
            'specific_actions': [
                'Build paper-mode (testnet OR mark-price-only fill)',
                'Run paper mode ≥ 7 days',
                'Compare BT prediction vs paper result: gap < 0.1%/day',
                'If gap > 0.1%/day → BT model has missing behavior, fix + re-BT',
                'Paper mode uses LIVE code path (not BT logic)',
            ],
            'pass_criterion': 'Paper trade gap < 0.1%/day for ≥7 days',
            'critical_note': 'R26+C1 두 번 같은 패턴 발생. Paper trade gate가 가장 결정적 prevention.',
        },
        'Gate_5_D_checkpoint_automation': {
            'required': True,
            'specific_actions': [
                'D-1: equity ≤ BT P5 → automatic halt + alert',
                'D-3: rolling 3d ≤ BT P5 → halt',
                'D-7: rolling 7d ≤ BT P5 → halt',
                'cron job (Windows Task Scheduler) for D-checks',
                'no human review required for halt trigger',
            ],
            'pass_criterion': 'cron jobs active, halt thresholds calibrated',
        },
    }


def pdca_plan_template(p: StrategyProposal, reality: dict, gate_prereqs: dict) -> str:
    """Generate PDCA Plan markdown template."""
    return f"""# PDCA Plan — {p.name}

> **Auto-generated by Strategy Lab pipeline.py on {datetime.utcnow().isoformat()}Z**

## 1. Strategy spec

| Field | Value |
|---|---|
| Mechanism | {p.feature.mechanism} |
| Substrate | {p.feature.substrate} |
| Execution | {p.feature.execution} |
| Friction profile | {p.feature.friction_profile} |
| Capital | ${p.capital_usd} |
| Expected freq | {p.feature.freq_tier} |
| Directionality | {p.feature.directionality} |
| Description | {p.description} |

## 2. Reality Filter verdict

| Dimension | Score | Detail |
|---|---|---|
{chr(10).join(f"| {dim} | {r['score']:.2f} | {r['detail']} |" for dim, r in reality['dimensions'].items())}

**Total**: {reality['total_score']:.2f}/{reality['max_score']} → **{reality['verdict']}** (level: {reality['level_eligible']})

## 3. 5-Gate Prereq Checklist

{chr(10).join(f"### {gname}{chr(10)}{chr(10)}{'**Required**: ' + str(g['required'])}{chr(10)}{chr(10)}**Actions**:{chr(10)}" + chr(10).join(f"  - [ ] {a}" for a in g.get('specific_actions', [])) + chr(10) + f"{chr(10)}**Pass criterion**: {g.get('pass_criterion', '')}{chr(10)}" + (f"{chr(10)}> {g.get('critical_note', '')}{chr(10)}" if g.get('critical_note') else "") for gname, g in gate_prereqs.items())}

## 4. PDCA progression

- [ ] **Plan** (this doc) — strategy spec + 5-gate checklist
- [ ] **Design** — Gate 1 audit table (LIVE↔BT 1:1 mapping)
- [ ] **Do (BT)** — Gate 2 statistical validation
- [ ] **Do (paper)** — Gate 4 paper trade ≥7d
- [ ] **Check** — gap analysis, halt thresholds calibration
- [ ] **Act** — Gate 5 cron jobs OR shelve

## 5. Reference rounds (Knowledge Base similar)

{chr(10).join(f"- {x['round_id']} (sim={x['similarity']:.3f}, {x['verdict']}): {x.get('falsification_reason') or ''}" for x in cross_check(p.feature)['top_5'])}

---
*Generated by `bingx_rl_trading_bot/scripts/strategy_lab/pipeline.py`*
"""


def evaluate_proposal(p: StrategyProposal) -> dict:
    """Full pipeline evaluation."""
    cc = cross_check(p.feature)
    reality = reality_eval(p)
    gate_prereqs = gate_prereq_template(p, reality)
    plan_md = pdca_plan_template(p, reality, gate_prereqs)
    return {
        'proposal': {
            'name': p.name,
            'feature': asdict(p.feature),
            'description': p.description,
        },
        'cross_check': cc,
        'reality': reality,
        'gate_prereqs': gate_prereqs,
        'plan_template_md': plan_md,
    }


def report_short(eval_result: dict):
    p = eval_result['proposal']
    r = eval_result['reality']
    cc = eval_result['cross_check']
    print('-' * 100)
    print(f'■ {p["name"]:<60}  → {r["verdict"]:<8}  ({r["total_score"]:.2f}/6, {r["level_eligible"]})')
    print(f'  most similar: {cc["most_similar_round"]:<35} sim={cc["max_similarity"]:.2f}  ({cc["most_similar_verdict"]})')
    if cc.get('reason'):
        print(f'  reason:       {cc["reason"][:100]}...' if len(cc.get('reason','')) > 100 else f'  reason:       {cc["reason"]}')


