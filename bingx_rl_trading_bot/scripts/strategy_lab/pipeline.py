"""Strategy Lab Pipeline — End-to-end ideation evaluator.

Input: a StrategyProposal
Output: Multi-level verdict (L1/L2/L3) + 5-gate prereq template + reasoning

Pipeline stages:
  1. Cross-check vs 28 rounds (early reject if variant of FALSIFIED)
  2. Reality filter 6-dim (block / caution / go)
  3. AST parity readiness (Gate 1 audit feasibility)
  4. Aggregate verdict + level eligibility
  5. PDCA Plan template auto-generation
"""
